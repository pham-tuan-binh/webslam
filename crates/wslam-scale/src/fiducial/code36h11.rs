//! AprilTag 36h11 payload layout, rotation algebra and codebook.
//!
//! # Scope limitation — read this before shipping
//!
//! The geometry in this crate (threshold, segmentation, quad fit, homography,
//! decode, pose) is a complete implementation. **The codebook is not the
//! canonical 587-entry `tag36h11` table.** Reproducing that table requires
//! Olson's randomised greedy search over the 2^36 code space, and the published
//! artifact is data, not an algorithm — it cannot be re-derived from its
//! parameters.
//!
//! What is here instead is a *generated* code set with the same parameters as
//! the family: 36 payload bits, a 6x6 data grid inside a one-cell black border,
//! and a minimum Hamming distance of 11 taken over all four rotations of every
//! pair, including each code against its own rotations. [`CODES`] is a frozen
//! table produced by [`generate_codes`], and its distance property is asserted
//! by test rather than asserted in prose.
//!
//! The consequence, stated plainly: **tags printed from the official
//! `tag36h11` family will not decode against this table, and our IDs are not
//! their IDs.** Swapping in the canonical table is a data change —
//! [`Codebook::from_codes`] takes it — and touches no decoding logic. Until
//! that happens, `FiducialScale` works against tags rendered by
//! [`crate::fiducial::render`], which is enough for the synthetic rig and the
//! Tier-1 suite but not for a printed target.

use wslam_core::DeterministicRng;

/// Payload bits in a 36h11 tag.
pub const NBITS: usize = 36;

/// Cells across the black-bordered square: 6 data cells plus one border cell
/// on each side. This square is what the detector's quad outlines, and what
/// `size_meters` measures.
pub const WIDTH_AT_BORDER: usize = 8;

/// Cells across the printed tag including the mandatory white quiet margin.
pub const TOTAL_WIDTH: usize = 10;

/// Minimum Hamming distance of the family, over all four rotations. The `11`
/// in "36h11".
pub const MIN_HAMMING: u32 = 11;

/// Mask covering the 36 payload bits.
pub const CODE_MASK: u64 = (1u64 << NBITS) - 1;

