/// `(column, row)` of every payload bit inside the 8x8 border square, MSB
/// first.
///
/// Bits spiral inwards in concentric rings — top row left to right, right
/// column top to bottom, bottom row right to left, left column bottom to top —
/// the same layout AprilTag 3 emits for its `h` families. The layout is not
/// cosmetic: a 90-degree rotation of the tag is a cyclic shift within each
/// ring, which is what makes rotation-invariant decoding cheap.
#[must_use]
pub fn bit_positions() -> [(usize, usize); NBITS] {
    let mut out = [(0usize, 0usize); NBITS];
    let mut i = 0;
    for ring in 0..3 {
        let lo = 1 + ring;
        let hi = WIDTH_AT_BORDER - 2 - ring;
        for x in lo..=hi {
            out[i] = (x, lo);
            i += 1;
        }
        for y in (lo + 1)..=hi {
            out[i] = (hi, y);
            i += 1;
        }
        for x in (lo..hi).rev() {
            out[i] = (x, hi);
            i += 1;
        }
        for y in ((lo + 1)..hi).rev() {
            out[i] = (lo, y);
            i += 1;
        }
    }
    debug_assert_eq!(i, NBITS);
    out
}

/// Permutation taking a code to its 90-degree clockwise rotation.
///
/// Rotating the tag image clockwise moves the cell at `(x, y)` to
/// `(W-1-y, x)`, so the rotated code's bit at position `p` is the original
/// code's bit at `(p.y, W-1-p.x)`.
fn rotation_permutation() -> [usize; NBITS] {
    let pos = bit_positions();
    let mut index_of = [[usize::MAX; WIDTH_AT_BORDER]; WIDTH_AT_BORDER];
    for (i, &(x, y)) in pos.iter().enumerate() {
        index_of[y][x] = i;
    }
    let mut perm = [0usize; NBITS];
    for (i, &(x, y)) in pos.iter().enumerate() {
        let (sx, sy) = (y, WIDTH_AT_BORDER - 1 - x);
        perm[i] = index_of[sy][sx];
        debug_assert_ne!(perm[i], usize::MAX, "rotation left the data grid");
    }
    perm
}

#[inline]
fn bit(code: u64, index: usize) -> u64 {
    (code >> (NBITS - 1 - index)) & 1
}

/// Rotate a payload 90 degrees clockwise.
#[must_use]
pub fn rotate90(code: u64) -> u64 {
    let perm = rotation_permutation();
    let mut out = 0u64;
    for (i, &src) in perm.iter().enumerate() {
        out |= bit(code, src) << (NBITS - 1 - i);
    }
    out
}

/// All four rotations of a payload, starting with the payload itself.
#[must_use]
pub fn rotations(code: u64) -> [u64; 4] {
    let r1 = rotate90(code);
    let r2 = rotate90(r1);
    let r3 = rotate90(r2);
    [code, r1, r2, r3]
}

/// Unpack a payload into the 6x6 data grid, indexed `[row][col]` with `true`
/// meaning a white cell.
#[must_use]
pub fn to_grid(code: u64) -> [[bool; 6]; 6] {
    let mut g = [[false; 6]; 6];
    for (i, &(x, y)) in bit_positions().iter().enumerate() {
        g[y - 1][x - 1] = bit(code, i) == 1;
    }
    g
}

/// Inverse of [`to_grid`].
#[must_use]
pub fn from_grid(grid: &[[bool; 6]; 6]) -> u64 {
    let mut code = 0u64;
    for (i, &(x, y)) in bit_positions().iter().enumerate() {
        if grid[y - 1][x - 1] {
            code |= 1u64 << (NBITS - 1 - i);
        }
    }
    code
}

/// Hamming distance between two payloads.
#[inline]
#[must_use]
pub fn hamming(a: u64, b: u64) -> u32 {
    ((a ^ b) & CODE_MASK).count_ones()
}

/// Minimum Hamming distance from `code` to every rotation of every entry in
/// `others`, and to `code`'s own non-identity rotations.
///
/// This is the quantity the "h11" in the family name bounds below.
#[must_use]
pub fn min_distance_over_rotations(code: u64, others: &[u64]) -> u32 {
    let mut best = u32::MAX;
    let rots = rotations(code);
    // Self-rotations: a code that matches its own rotation decodes with an
    // ambiguous orientation, which would silently corrupt the recovered pose.
    for r in &rots[1..] {
        best = best.min(hamming(code, *r));
    }
    for &o in others {
        for r in rotations(o) {
            best = best.min(hamming(code, r));
        }
    }
    best
}

/// Greedily build a code set with the 36h11 distance property.
///
/// Candidates are drawn from a seeded stream (spec.md §6: *"Every RNG is
/// seeded"*) and accepted when [`min_distance_over_rotations`] is at least
/// [`MIN_HAMMING`]. Deterministic: the same `(count, budget, seed)` always
/// produces the same table, which is what makes [`CODES`] auditable.
#[must_use]
pub fn generate_codes(count: usize, candidate_budget: usize, seed: u64) -> Vec<u64> {
    let mut rng = DeterministicRng::new("tag36h11-codebook", seed);
    let mut accepted: Vec<u64> = Vec::with_capacity(count);
    for _ in 0..candidate_budget {
        if accepted.len() == count {
            break;
        }
        // 36 bits from two 32-bit draws' worth of uniform entropy.
        let hi = (rng.uniform() * ((1u64 << 18) as f64)) as u64 & 0x3ffff;
        let lo = (rng.uniform() * ((1u64 << 18) as f64)) as u64 & 0x3ffff;
        let candidate = ((hi << 18) | lo) & CODE_MASK;
        if min_distance_over_rotations(candidate, &accepted) >= MIN_HAMMING {
            accepted.push(candidate);
        }
    }
    accepted
}

/// A decodable set of payloads.
#[derive(Debug, Clone)]
pub struct Codebook {
    codes: Vec<u64>,
    rotations: Vec<[u64; 4]>,
}

/// A payload matched against a [`Codebook`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Match {
    /// Index into the codebook — the tag ID.
    pub id: u32,
    /// Quarter turns the observed payload is rotated relative to the stored
    /// one. Rotating the detected corner list by this many positions puts
    /// corner 0 back on the tag's canonical first corner.
    pub rotation: u8,
    /// Bit errors corrected.
    pub hamming: u32,
}

impl Default for Codebook {
    fn default() -> Self {
        Self::standard()
    }
}

impl Codebook {
    /// The frozen [`CODES`] table.
    #[must_use]
    pub fn standard() -> Self {
        Self::from_codes(CODES)
    }

    /// Build from an explicit table. This is the seam through which the
    /// canonical 587-entry `tag36h11` table drops in as data.
    #[must_use]
    pub fn from_codes(codes: &[u64]) -> Self {
        let codes: Vec<u64> = codes.iter().map(|c| c & CODE_MASK).collect();
        let rotations = codes.iter().map(|&c| rotations(c)).collect();
        Codebook { codes, rotations }
    }

    /// Number of distinct tag IDs.
    #[must_use]
    pub fn len(&self) -> usize {
        self.codes.len()
    }

    /// Whether the codebook is empty.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.codes.is_empty()
    }

    /// The payload for a tag ID.
    #[must_use]
    pub fn code(&self, id: u32) -> Option<u64> {
        self.codes.get(id as usize).copied()
    }

    /// Nearest codebook entry within `max_hamming` bits, over all rotations.
    ///
    /// `max_hamming` is a false-positive control, not an error-correction
    /// budget: the family could correct five bit errors, but every extra bit
    /// of slack multiplies the chance that a random quad in the scene decodes
    /// as a tag. spec.md §5 makes the analogous point for loop closure — a
    /// false positive is worse than no detection at all — and a false fiducial
    /// corrupts scale just as silently.
    #[must_use]
    pub fn lookup(&self, observed: u64, max_hamming: u32) -> Option<Match> {
        let observed = observed & CODE_MASK;
        let mut best: Option<Match> = None;
        for (id, rots) in self.rotations.iter().enumerate() {
            for (rot, &r) in rots.iter().enumerate() {
                let d = hamming(observed, r);
                if d <= max_hamming && best.is_none_or(|b| d < b.hamming) {
                    best = Some(Match {
                        id: id as u32,
                        rotation: rot as u8,
                        hamming: d,
                    });
                }
            }
        }
        best
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn bit_layout_covers_the_six_by_six_data_grid_exactly_once() {
        let pos = bit_positions();
        let unique: HashSet<(usize, usize)> = pos.iter().copied().collect();
        assert_eq!(unique.len(), NBITS);
        for &(x, y) in &pos {
            assert!(
                (1..=6).contains(&x) && (1..=6).contains(&y),
                "({x},{y}) outside data grid"
            );
        }
    }

    #[test]
    fn rotation_permutation_is_a_bijection() {
        let perm = rotation_permutation();
        let unique: HashSet<usize> = perm.iter().copied().collect();
        assert_eq!(unique.len(), NBITS);
    }

    /// The cheap ring-shift rotation must agree with the geometric truth:
    /// unpack to a grid, rotate the grid, repack.
    #[test]
    fn rotate90_matches_an_explicit_grid_rotation() {
        for code in [0x123456789u64, 0xfedcba987, 0x0, CODE_MASK, 0xa5a5a5a5a] {
            let g = to_grid(code & CODE_MASK);
            let mut rotated = [[false; 6]; 6];
            // Clockwise: new[r][c] = old[5-c][r].
            for (r, row) in rotated.iter_mut().enumerate() {
                for (c, cell) in row.iter_mut().enumerate() {
                    *cell = g[5 - c][r];
                }
            }
            assert_eq!(
                rotate90(code & CODE_MASK),
                from_grid(&rotated),
                "code {code:#x}"
            );
        }
    }

    #[test]
    fn four_rotations_return_to_the_original() {
        for code in [0x0u64, CODE_MASK, 0xdeadbeef1, 0x1, 0x800000000] {
            let c = code & CODE_MASK;
            assert_eq!(rotate90(rotate90(rotate90(rotate90(c)))), c);
        }
    }

    #[test]
    fn grid_roundtrip() {
        for code in [0x0u64, CODE_MASK, 0x9e3779b97 & CODE_MASK, 0x555555555] {
            assert_eq!(from_grid(&to_grid(code)), code);
        }
    }

    /// The "h11" in the family name, asserted rather than asserted-in-prose.
    #[test]
    fn codebook_has_minimum_hamming_distance_eleven() {
        assert!(CODES.len() >= 32, "table is suspiciously small");
        let unique: HashSet<u64> = CODES.iter().copied().collect();
        assert_eq!(unique.len(), CODES.len(), "duplicate codes");

        for (i, &c) in CODES.iter().enumerate() {
            let others: Vec<u64> = CODES
                .iter()
                .enumerate()
                .filter(|(j, _)| *j != i)
                .map(|(_, &v)| v)
                .collect();
            let d = min_distance_over_rotations(c, &others);
            assert!(
                d >= MIN_HAMMING,
                "code {i} ({c:#x}) is only {d} bits from another codeword or its own rotation"
            );
        }
    }

    /// The table is reproducible from its stated generator arguments, so its
    /// provenance is checkable rather than asserted.
    #[test]
    fn generated_table_is_reproducible() {
        let regenerated = generate_codes(8, 1 << 22, 20260801);
        assert_eq!(regenerated.len(), 8);
        assert_eq!(&regenerated[..], &CODES[..8]);
    }

    #[test]
    fn lookup_recovers_id_and_rotation_from_a_rotated_payload() {
        let book = Codebook::standard();
        for id in [0u32, 1, 7, 31, (CODES.len() - 1) as u32] {
            let code = book.code(id).unwrap();
            for (rot, observed) in rotations(code).iter().enumerate() {
                let m = book.lookup(*observed, 0).expect("exact payload must match");
                assert_eq!(m.id, id);
                assert_eq!(m.rotation, rot as u8);
                assert_eq!(m.hamming, 0);
            }
        }
    }

    #[test]
    fn lookup_corrects_bit_errors_up_to_the_budget() {
        let book = Codebook::standard();
        let code = book.code(3).unwrap();
        // Flip two bits.
        let corrupted = code ^ 0b101;
        assert_eq!(book.lookup(corrupted, 2).map(|m| m.id), Some(3));
        assert_eq!(book.lookup(corrupted, 2).map(|m| m.hamming), Some(2));
        // ... and refuses when the budget is smaller than the error.
        assert!(book.lookup(corrupted, 1).is_none());
    }

    /// False positives here corrupt scale silently, so a payload that is not a
    /// codeword must not resolve to one. With d = 11 the nearest codeword to a
    /// random payload is 13-18 bits away in practice.
    #[test]
    fn random_payloads_do_not_decode() {
        let book = Codebook::standard();
        let mut rng = DeterministicRng::new("false-positive-probe", 4242);
        let mut hits = 0;
        for _ in 0..20_000 {
            let hi = (rng.uniform() * ((1u64 << 18) as f64)) as u64 & 0x3ffff;
            let lo = (rng.uniform() * ((1u64 << 18) as f64)) as u64 & 0x3ffff;
            if book.lookup(((hi << 18) | lo) & CODE_MASK, 2).is_some() {
                hits += 1;
            }
        }
        assert_eq!(hits, 0, "{hits} random payloads decoded as tags");
    }

    #[test]
    fn empty_codebook_never_matches() {
        let book = Codebook::from_codes(&[]);
        assert!(book.is_empty());
        assert_eq!(book.len(), 0);
        assert!(book.lookup(0, 36).is_none());
        assert!(book.code(0).is_none());
    }
}
